// materials.js — the shared library of photographed (CC0, Poly Haven) PBR
// materials and the real sky. Every space in the complex builds from these, so
// the whole place reads as one consistent, physically lit world.
//
//   const M = createMaterials(renderer, { quality });
//   const mat = M.get('paving');                 // MeshStandardMaterial, textures stream in
//   M.boxUV(geometry);                           // UVs in metres, so textures keep real scale
//   const { background, environment, sunDirection } = await M.sky();
//   const { background, environment } = await M.overcast();   // storm sky, loaded on first call
//
// UV convention: 1 UV unit = 1 metre. Each material carries its real-world tile
// size, so call M.boxUV(geometry) (or write metre UVs yourself) on every
// geometry that uses a textured material.
//
// Loading (the hall comes first, the campus streams in behind it):
// - Nothing here downloads until the page's load event (the hall's works are
//   in) or 10 s at the latest, so the campus never competes with the entry.
// - The sky's light comes from a 1k HDR (sky-1k.hdr, 1.4 MB): the background
//   starts from it and is sharpened in place to the 2k photograph, after the
//   textures, once `sky.sharp` is read ('low' keeps the 1k one).
// - Textures download a few at a time at low priority, are decoded off the main
//   thread (createImageBitmap) where the browser does that reliably, and reach
//   the GPU a few per frame, so the arrival of the campus causes no hitches.
// - quality 'high' uses the 1k maps; 'medium' 512 px maps; 'low' 512 px base
//   colour only (generated by scripts/fetch-textures.py --variants).
// Maps are uploaded to the GPU once and their decoded copy is then released:
// clone a map before changing its wrapping, filtering or anisotropy.
import * as THREE from 'three';
import { RGBELoader } from 'three/addons/loaders/RGBELoader.js';

const BASE = new URL('../textures/', import.meta.url);

