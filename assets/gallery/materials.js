export const MATERIAL_NAMES = Object.keys(LIBRARY);

// Network: a few downloads at a time keeps the line full without starving
// anything else (prefetched works, the storm sky) of bandwidth.
const MAX_DOWNLOADS = 6;
// Main thread: GPU uploads per animation frame, within a small time budget.
const UPLOAD_BUDGET_MS = 6;

// createImageBitmap decodes off the main thread; Safari < 17 and Firefox < 98
// get it wrong (orientation / options), so they keep the <img> path.
const UA = typeof navigator !== 'undefined' ? navigator.userAgent : '';
const SAFARI = /^((?!chrome|android).)*safari/i.test(UA) ? Number((UA.match(/version\/(\d+)/i) || [])[1] || 0) : -1;
const FIREFOX = Number((UA.match(/firefox\/(\d+)/i) || [])[1] || -1);
const BITMAPS = typeof createImageBitmap === 'function' && typeof fetch === 'function'
  && !(SAFARI >= 0 && SAFARI < 17) && !(FIREFOX >= 0 && FIREFOX < 98);

// The hall's works are <img> loads, which hold the page's load event: start
// the campus's downloads when it fires (or after 10 s, whichever is first).
let hallFirst = null;
function afterHall() {
  if (!hallFirst) {
    hallFirst = new Promise((resolve) => {
      if (typeof document === 'undefined' || document.readyState === 'complete') { resolve(); return; }
      addEventListener('load', () => resolve(), { once: true });
      setTimeout(resolve, 10000);
    });
  }
  return hallFirst;
}

export function createMaterials(renderer, { quality = 'high' } = {}) {
  const tier = quality === 'low' || quality === 'medium' ? quality : 'high';
  const suffix = tier === 'high' ? '' : '-512';
  const anisotropy = renderer.capabilities.getMaxAnisotropy();
  const textures = new Map();     // `${id}/${kind}` -> Texture (shared image)
  const views = new Map();        // shared Texture -> its per-material views
  const uploaded = new Set();     // shared Textures whose image is on the GPU
  const materials = new Map();    // cache key -> material
  const imgLoader = new THREE.TextureLoader();

  // ---- download queue: priority 0 sky light, 1 textures, 2 sharper background
  const queue = [];
  let active = 0;
  function download(priority, job) {
    return new Promise((resolve, reject) => {
      queue.push({ priority, job, resolve, reject });
      queue.sort((a, b) => a.priority - b.priority);   // stable: keeps request order within a priority
      afterHall().then(pump);
    });
  }
  function pump() {
    while (active < MAX_DOWNLOADS && queue.length) {
      const { job, resolve, reject } = queue.shift();
      active++;
      Promise.resolve().then(job).then(resolve, reject).finally(() => { active--; pump(); });
    }
  }
  const idle = (fn) => (typeof requestIdleCallback === 'function' ? requestIdleCallback(fn, { timeout: 1500 }) : setTimeout(fn, 60));

  // ---- GPU uploads, paced across frames
  const uploads = [];
  let uploading = false;
  function scheduleUpload(src) {
    uploads.push(src);
    if (uploading) return;
    uploading = true;
    const frame = () => {
      const t0 = performance.now();
      while (uploads.length && (performance.now() - t0 < UPLOAD_BUDGET_MS)) upload(uploads.shift());
      if (uploads.length) requestAnimationFrame(frame); else uploading = false;
    };
    requestAnimationFrame(frame);
  }
  function upload(src) {
    const list = views.get(src);
    src.needsUpdate = true;                            // one new image version for the shared source…
    for (const v of list) v.version++;                // …and every view picks it up without re-uploading
    uploaded.add(src);
    try { renderer.initTexture(list[0] || src); } catch (e) { /* uploads at first use instead */ }
  }

  function loadBitmap(url) {
    return download(1, () => fetch(url, { priority: 'low' }).then((r) => {
      if (!r.ok) throw new Error(`${r.status} ${url}`);
      return r.blob();
    })).then((blob) => createImageBitmap(blob, { imageOrientation: 'flipY', premultiplyAlpha: 'none', colorSpaceConversion: 'none' }));
  }

  function texture(id, kind) {
    const key = `${id}/${kind}`;
    if (!textures.has(key)) {
      const url = new URL(`${id}/${kind}${suffix}.webp`, BASE).href;
      const t = new THREE.Texture();
      t.wrapS = t.wrapT = THREE.RepeatWrapping;
      t.anisotropy = anisotropy;
      t.colorSpace = kind === 'diff' ? THREE.SRGBColorSpace : THREE.NoColorSpace;
      textures.set(key, t);
      views.set(t, []);
      const viaImg = () => download(1, () => imgLoader.loadAsync(url)).then((img) => {
        t.flipY = true;
        for (const v of views.get(t)) v.flipY = true;
        t.image = img.image;
        scheduleUpload(t);
      });
      if (BITMAPS) {
        t.flipY = false;                                 // the bitmap is decoded already flipped
        loadBitmap(url).then((bitmap) => {
          t.image = bitmap;
          // Keep the decoded copy only until the GPU has it.
          const release = () => { if (t.image === bitmap) bitmap.close?.(); };
          t.onUpdate = release;
          for (const v of views.get(t)) v.onUpdate = release;
          scheduleUpload(t);
        }).catch(() => viaImg().catch((err) => console.warn(`[materials] ${url} failed`, err)));
      } else {
        viaImg().catch((err) => console.warn(`[materials] ${url} failed`, err));
      }
    }
    return textures.get(key);
  }

  // A per-material view of a shared texture: own repeat, same GPU image.
  function view(id, kind, repeat) {
    const src = texture(id, kind);
    const version = src.source.version;
    const t = src.clone();               // shares src.source, so the image arrives by itself
    src.source.version = version;        // clone() marks the shared image dirty: it is not
    t.repeat.set(repeat, repeat);
    t.onUpdate = src.onUpdate;
    if (!uploaded.has(src)) t.version = 0;   // nothing to upload yet: upload() wakes it
    views.get(src).push(t);
    return t;
  }

  /**
   * get(name, { tile, color, roughness, metalness, side, transparent, opacity, envMapIntensity })
   * `tile` overrides the real-world tile size in metres.
   */
  function get(name, opts = {}) {
    const entry = LIBRARY[name];
    if (!entry) throw new Error(`Unknown material "${name}". Known: ${MATERIAL_NAMES.join(', ')}`);
    const key = name + JSON.stringify(opts);
    if (materials.has(key)) return materials.get(key);
    const [id, tile, extra] = entry;
    const repeat = 1 / (opts.tile || tile);
    const params = {
      map: view(id, 'diff', repeat),
      roughness: 1, metalness: 0,
      ...withoutNormalScale(extra),
    };
    if (opts.color !== undefined) params.color = opts.color;
    const mat = new THREE.MeshStandardMaterial(params);
    if (tier !== 'low') {
      const arm = view(id, 'arm', repeat);
      mat.normalMap = view(id, 'nor', repeat);
      const ns = extra.normalScale ?? 1;
      mat.normalScale.set(ns, ns);
      mat.roughnessMap = arm;
      mat.aoMap = arm;
      mat.aoMapIntensity = 0.85;
      if ((extra.metalness ?? 0) > 0) mat.metalnessMap = arm;
    }
    for (const k of ['roughness', 'metalness', 'side', 'transparent', 'opacity', 'envMapIntensity']) {
      if (opts[k] !== undefined) mat[k] = opts[k];
    }
    mat.name = name;
    materials.set(key, mat);
    return mat;
  }

  // ---- skies
  // Light and sun from the 1k HDR (fast). The background can then be sharpened
  // in place to the 2k file (same Texture object, so whoever holds it needs no
  // change): the storm sky does that by itself; the sunny one when someone reads
  // `sky.sharp` (weather draws environment.js's sun-less copy of it, not it).
  function loadSky(small, large, priority) {
    const hdrAt = (file) => new RGBELoader().loadAsync(new URL(file, BASE).href);
    let full = false;
    return download(priority, () => hdrAt(small).catch(() => { full = true; return hdrAt(large); })).then((hdr) => {
      hdr.mapping = THREE.EquirectangularReflectionMapping;
      const pmrem = new THREE.PMREMGenerator(renderer);
      const environment = pmrem.fromEquirectangular(hdr).texture;
      pmrem.dispose();
      let sharp = null;
      const sharpened = () => (sharp ||= (tier === 'low' || full) ? Promise.resolve(hdr) : sharpen(hdr, large));
      return { hdr, environment, sharpened };
    });
  }
  // Resolves with `hdr` once it holds the 2k photograph (or still the 1k one, if that failed).
  function sharpen(hdr, file) {
    return download(2, () => fetch(new URL(file, BASE).href, { priority: 'low' }).then((r) => {
      if (!r.ok) throw new Error(`${r.status} ${file}`);
      return r.arrayBuffer();
    })).then((buffer) => new Promise((resolve) => idle(() => {
      const loader = new RGBELoader().setDataType(hdr.type);
      const big = loader.parse(buffer);
      hdr.dispose();                       // drops the small GPU copy and three's cube of it
      hdr.image = { data: big.data, width: big.width, height: big.height };
      hdr.needsUpdate = true;
      resolve(hdr);
    }))).catch((err) => { console.warn(`[materials] ${file} failed; keeping the 1k sky`, err); return hdr; });
  }

  let skyPromise = null;
  /**
   * The real sky: an HDR photograph used as background and as image-based light.
   * { background, environment, sunDirection, sharp }: reading `sharp` (a Promise
   * of `background`) fetches the 2k photograph into `background`, in place.
   */
  function sky() {
    if (!skyPromise) {
      skyPromise = loadSky('sky-1k.hdr', 'sky.hdr', 0).then(({ hdr, environment, sharpened }) => ({
        background: hdr, environment, sunDirection: findSun(hdr),
        get sharp() { return sharpened(); },
      }));
    }
    return skyPromise;
  }

  let overcastPromise = null;
  /** The storm sky ({ background, environment, sharp }), downloaded on the first call only. */
  function overcast() {
    if (!overcastPromise) {
      overcastPromise = loadSky('sky-overcast-1k.hdr', 'sky-overcast.hdr', 0).then(({ hdr, environment, sharpened }) => (
        { background: hdr, environment, sharp: sharpened() }
      ));
      overcastPromise.catch(() => { overcastPromise = null; });
    }
    return overcastPromise;
  }

  return { get, texture, sky, overcast, boxUV, names: MATERIAL_NAMES };
}

function withoutNormalScale(extra) {
  const { normalScale, ...rest } = extra;
  return rest;
}

/**
 * Rewrites a geometry's UVs as metres, projected along each vertex's dominant
 * normal axis (box mapping). Call after any scaling baked into the geometry.
 * `offset` shifts the pattern (e.g. so adjoining pieces don't repeat visibly).
 */
export function boxUV(geometry, { scale = 1, offset = [0, 0] } = {}) {
  const pos = geometry.attributes.position;
  if (!geometry.attributes.normal) geometry.computeVertexNormals();
  const nor = geometry.attributes.normal;
  const uv = new Float32Array(pos.count * 2);
  for (let i = 0; i < pos.count; i++) {
    const nx = Math.abs(nor.getX(i)), ny = Math.abs(nor.getY(i)), nz = Math.abs(nor.getZ(i));
    const x = pos.getX(i), y = pos.getY(i), z = pos.getZ(i);
    let u, v;
    if (ny >= nx && ny >= nz) { u = x; v = z; }
    else if (nx >= nz) { u = z; v = y; }
    else { u = x; v = y; }
    uv[i * 2] = u * scale + offset[0];
    uv[i * 2 + 1] = v * scale + offset[1];
  }
  geometry.setAttribute('uv', new THREE.BufferAttribute(uv, 2));
  return geometry;
}

// The brightest region of the equirectangular sky is the sun: point the
// DirectionalLight there so shadows agree with the photograph.
function findSun(hdr) {
  const { data, width, height } = hdr.image;
  const stride = data.length / (width * height);
  const step = width >= 2048 ? 2 : 1;          // the 1k sky's sun is only a texel or two wide
  let best = -1, bx = 0, by = 0;
  const toFloat = data instanceof Uint16Array ? THREE.DataUtils.fromHalfFloat : (x) => x;
  for (let y = 0; y < height / 2; y += step) {
    for (let x = 0; x < width; x += step) {
      const i = (y * width + x) * stride;
      const l = toFloat(data[i]) + toFloat(data[i + 1]) + toFloat(data[i + 2]);
      if (l > best) { best = l; bx = x; by = y; }
    }
  }
  const phi = (bx / width) * Math.PI * 2;      // around
  const theta = (by / height) * Math.PI;       // from the zenith
  // Matches three's equirectangular convention.
  return new THREE.Vector3(-Math.sin(theta) * Math.cos(phi), Math.cos(theta), -Math.sin(theta) * Math.sin(phi)).normalize();
}
